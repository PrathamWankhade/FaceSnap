#!/usr/bin/env python
"""Email the attendance report as a CSV attachment (dry run by default).

    python scripts/email_report.py --days 7            # print CSV to stdout
    python scripts/email_report.py --days 7 --apply    # email it

Sending requires ``REPORT_EMAIL_TO`` plus the ``SMTP_*`` settings (see
``docs/monitoring.md``). Defaults to a dry run so a misconfigured cron never
mails anyone by accident. Intended for cron / a scheduler:

    0 7 * * *  cd /srv/facesnap/backend && .venv/bin/python scripts/email_report.py --days 1 --apply
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def build_rows(db, days: int, limit: int = 5000):
    from sqlalchemy import select

    from app.db import Attendance, utcnow

    cutoff = utcnow() - timedelta(days=days)
    stmt = (
        select(Attendance)
        .where(Attendance.captured_at >= cutoff)
        .order_by(Attendance.captured_at.desc())
        .limit(limit)
    )
    return db.scalars(stmt).all()


def send_csv(csv_text: str, days: int) -> None:
    """Email the CSV as an attachment. Raises on failure (caller reports)."""
    import smtplib
    from email.message import EmailMessage

    from app.config import (
        REPORT_EMAIL_TO,
        SMTP_FROM,
        SMTP_HOST,
        SMTP_PASSWORD,
        SMTP_PORT,
        SMTP_USE_TLS,
        SMTP_USER,
    )
    from app.db import utcnow

    msg = EmailMessage()
    msg["Subject"] = f"FaceSnap attendance report (last {days} days)"
    msg["From"] = SMTP_FROM
    msg["To"] = REPORT_EMAIL_TO
    msg.set_content(
        "Attached is the FaceSnap attendance CSV for the requested window.\n"
        "Generated by scripts/email_report.py."
    )
    filename = f"facesnap-attendance-{utcnow().date().isoformat()}.csv"
    msg.add_attachment(
        csv_text.encode("utf-8"),
        maintype="text",
        subtype="csv",
        filename=filename,
    )

    with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=15) as server:
        if SMTP_USE_TLS:
            server.starttls()
        if SMTP_USER:
            server.login(SMTP_USER, SMTP_PASSWORD)
        server.send_message(msg)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--days",
        type=int,
        default=7,
        help="report window in days (default: 7)",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="actually email the report; without this flag only print the CSV",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=5000,
        help="maximum rows (default: 5000)",
    )
    args = parser.parse_args(argv)

    if args.days <= 0:
        print("--days must be a positive number of days.", file=sys.stderr)
        return 2

    from app.config import REPORT_EMAIL_TO, SMTP_HOST
    from app.db import SessionLocal
    from app.services.reports import attendance_csv

    with SessionLocal() as db:
        rows = build_rows(db, args.days, args.limit)
        # Render while the session is still open: attendance_csv lazy-loads
        # record.student, which raises DetachedInstanceError afterwards.
        csv_text = attendance_csv(rows)

    if not args.apply:
        print(csv_text, end="")
        print(
            "\nDry run: nothing sent. Re-run with --apply to email it.",
            file=sys.stderr,
        )
        return 0

    if not REPORT_EMAIL_TO or not SMTP_HOST:
        print(
            "REPORT_EMAIL_TO and SMTP_HOST are required to send. "
            "Refusing to guess a recipient.",
            file=sys.stderr,
        )
        return 2

    try:
        send_csv(csv_text, args.days)
    except Exception as exc:  # noqa: BLE001 - CLI reports, does not traceback
        print(f"Send failed: {exc}", file=sys.stderr)
        return 1

    print(json.dumps({"sent": True, "rows": len(rows), "days": args.days}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
